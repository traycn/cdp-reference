"""docs/results.md, written only from `cdp-stitch evaluate` output (one JSON per seed).

Nothing in the page is typed by hand, and nothing in it varies between runs of
the same code on the same seeds (no timings), so CI's reproduce job can diff a
regenerated copy against the committed one. Two bars are known misses, explained
in ADRs and reported rather than failed: wrong attachment (ADR 0004) and
same-name relatives with both DOBs present merged (ADR 0001).
"""

from __future__ import annotations

import json
from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Any

from cdp_stitch.db import DATA_DIR
from cdp_stitch.evaluate import (
    BAR_ATTACHMENT,
    BAR_COMPLETENESS,
    BAR_PRECISION,
    BAR_PRECISION_MEAN,
    BAR_SAFETY,
    BAR_SAME_NAME_BOTH_DOB_MERGED,
    BAR_WRONG_ATTACHMENT,
    DOB_GROUPS,
    HAZARD_KINDS,
    failures,
)

Metrics = dict[str, Any]

ADR_0001 = "adr/0001-reuse-entity-resolution.md#consequences"
ADR_0004 = "adr/0004-device-attachment.md"
EXPLAINED_0001 = f"miss (explained, [ADR 0001]({ADR_0001}))"
EXPLAINED_0004 = f"miss (explained, [ADR 0004]({ADR_0004}))"

RULE_NAMES = {
    "unanimous": "(a) unanimous",
    "majority": "(b) majority",
    "nearest": "(c) nearest",
    "session_majority": "(d) session + majority",
    "session_strict": "(e) session, strict",
}
ADOPTED_RULE = "session_majority"


def load_metrics(eval_dir: Path, seeds: Sequence[int]) -> list[Metrics]:
    return [json.loads((eval_dir / f"eval-{s}.json").read_text(encoding="utf-8")) for s in seeds]


def load_manifests(seeds: Sequence[int]) -> list[dict[str, Any]]:
    return [
        json.loads((DATA_DIR / f"seed-{s}" / "manifest.json").read_text(encoding="utf-8"))
        for s in seeds
    ]


def mean(values: Sequence[float]) -> float:
    return sum(values) / len(values)


def run_failures(ms: Sequence[Metrics]) -> list[str]:
    """Bars that fail CI: per seed (evaluate.failures) and mean non-hazard precision."""
    out = [f for m in ms for f in failures(m)]
    p = mean([m["precision"]["rate"] for m in ms])
    if p < BAR_PRECISION_MEAN:
        out.append(f"mean non-hazard precision {p:.4f} < {BAR_PRECISION_MEAN:.2f}")
    return out


def _f(x: float) -> str:
    return f"{x:.4f}"


def _table(header: Sequence[str], align: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(align) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def render(ms: Sequence[Metrics], manifests: Sequence[dict[str, Any]]) -> str:
    seeds = [m["seed"] for m in ms]
    engine = ms[0]["engine"]
    if any(m["engine"] != engine for m in ms):
        raise RuntimeError("seeds were evaluated with different engine builds")
    seed_cols = [str(s) for s in seeds]
    out: list[str] = []
    add = out.append

    add("# Results")
    add("")
    add(
        "Generated by `cdp-stitch report` from `cdp-stitch evaluate` output. Do not edit by "
        "hand: CI's `reproduce` job regenerates this file from scratch and fails on any "
        "difference. Bars and their definitions: [`acceptance.md`](acceptance.md)."
    )
    add("")
    add(f"- **Engine:** {engine['name']} `{engine['version']}` (commit `{engine['commit']}`).")
    add(
        "- **Device rule:** (d) session + majority ([ADR 0004](" + ADR_0004 + ")). "
        "Generator version "
        + ", ".join(sorted({str(mf["generator_version"]) for mf in manifests}))
        + "."
    )
    add(
        "- **Seeds:** development seeds "
        + ", ".join(seed_cols)
        + ", 10,000 people each, `--dob-rate "
        + ", ".join(sorted({str(mf["dob_rate"]) for mf in manifests}))
        + "`. Held-out seeds have not been run: the thresholds are not frozen yet "
        "(no `acceptance-frozen` tag)."
    )
    add("")
    add(
        _table(
            ["Seed", "Generator output SHA-256"],
            ["---", "---"],
            [[str(mf["seed"]), f"`{mf['sha256']}`"] for mf in manifests],
        )
    )
    add("")

    # -- bars -------------------------------------------------------------
    add("## M3 identity bars")
    add("")
    add(
        "Each cell is the seed's value, then ✓ (meets the bar) or ✗ (misses it). "
        "Status covers all seeds. The two known misses are reported here and in CI, "
        "not failed; every other bar fails CI's `stitch-eval` job when missed."
    )
    add("")

    rows: list[list[str]] = []

    def bar_row(
        name: str,
        bar: str,
        value: Callable[[Metrics], str],
        ok: Callable[[Metrics], bool],
        explained: str | None = None,
    ) -> None:
        cells = [f"{value(m)} {'✓' if ok(m) else '✗'}" for m in ms]
        passed = all(ok(m) for m in ms)
        status = "pass" if passed else explained or "**miss**"
        rows.append([name, bar, *cells, status])

    def sn_both(m: Metrics) -> dict[str, int]:
        cell: dict[str, int] = m["hard_cases"]["same_name_relative"]["both"]
        return cell

    bar_row(
        "Pairwise precision, non-hazard",
        f"≥ {BAR_PRECISION:.2f}",
        lambda m: _f(m["precision"]["rate"]),
        lambda m: m["precision"]["rate"] >= BAR_PRECISION,
    )
    bar_row(
        "Same-name relatives, both DOBs present, merged",
        str(BAR_SAME_NAME_BOTH_DOB_MERGED),
        lambda m: f"{sn_both(m)['merged']}/{sn_both(m)['pairs']}",
        lambda m: sn_both(m)["merged"] <= BAR_SAME_NAME_BOTH_DOB_MERGED,
        EXPLAINED_0001,
    )
    bar_row(
        "Person completeness",
        f"≥ {BAR_COMPLETENESS:.2f}",
        lambda m: _f(m["completeness"]["combined"]["rate"]),
        lambda m: m["completeness"]["combined"]["rate"] >= BAR_COMPLETENESS,
    )
    bar_row(
        "Safety (unsafe profiles)",
        str(BAR_SAFETY),
        lambda m: str(m["safety"]["unsafe_profiles"]),
        lambda m: m["safety"]["unsafe_profiles"] <= BAR_SAFETY,
    )
    bar_row(
        "Event attachment",
        f"≥ {BAR_ATTACHMENT:.2f}",
        lambda m: _f(m["event_attachment"]["rate"]),
        lambda m: m["event_attachment"]["rate"] >= BAR_ATTACHMENT,
    )
    bar_row(
        "Wrong attachment",
        f"≤ {BAR_WRONG_ATTACHMENT:.3f}",
        lambda m: _f(m["event_attachment"]["wrong_rate"]),
        lambda m: m["event_attachment"]["wrong_rate"] <= BAR_WRONG_ATTACHMENT,
        EXPLAINED_0004,
    )
    add(
        _table(
            ["Metric", "Bar", *seed_cols, "Status"],
            ["---", "---", *["---:"] * len(ms), "---"],
            rows,
        )
    )
    add("")

    nh = mean([m["precision"]["rate"] for m in ms])
    ap = mean([m["precision_all_pairs"]["rate"] for m in ms])
    add(
        _table(
            ["Across seeds", "Bar", "Value", "Status"],
            ["---", "---", "---:", "---"],
            [
                [
                    "Mean pairwise precision, non-hazard",
                    f"≥ {BAR_PRECISION_MEAN:.2f}",
                    _f(nh),
                    "pass" if nh >= BAR_PRECISION_MEAN else "**miss**",
                ],
            ],
        )
    )
    add("")

    # -- report-only --------------------------------------------------------
    add("## Reported, no bar")
    add("")
    add(
        "All-pairs precision is reported against the original bar (≥ "
        f"{BAR_PRECISION:.2f} per seed, ≥ {BAR_PRECISION_MEAN:.2f} mean), which applied to "
        "all pairs until the change of 2026-10-22, so the original miss stays visible."
    )
    add("")
    report_rows: list[list[str]] = []

    def report_row(name: str, value: Callable[[Metrics], str]) -> None:
        report_rows.append([name, *[value(m) for m in ms]])

    report_row(
        f"Pairwise precision, all pairs (original bar ≥ {BAR_PRECISION:.2f})",
        lambda m: (
            f"{_f(m['precision_all_pairs']['rate'])} "
            + ("✓" if m["precision_all_pairs"]["rate"] >= BAR_PRECISION else "✗")
        ),
    )
    report_row("Pairwise recall", lambda m: _f(m["recall"]["rate"]))

    def completeness_of(kind: str) -> Callable[[Metrics], str]:
        return lambda m: _f(m["completeness"]["by_kind"][kind]["rate"])

    for kind in ("ordinary", "multi_email", "multi_device", "email_changed"):
        report_row(f"Completeness, `{kind}`", completeness_of(kind))
    report_row(
        "Same-name relatives, a DOB missing, merged",
        lambda m: (
            f"{sum(m['hard_cases']['same_name_relative'][g]['merged'] for g in ('one', 'none'))}"
            f"/{sum(m['hard_cases']['same_name_relative'][g]['pairs'] for g in ('one', 'none'))}"
        ),
    )
    report_row(
        "Device conflicts (tie for most fills, no device link)",
        lambda m: f"{m['device_conflicts']:,}",
    )
    report_row("Profiles", lambda m: f"{m['counts']['profiles']:,}")
    report_row("Person records", lambda m: f"{m['counts']['person_records']:,}")
    add(_table(["Metric", *seed_cols], ["---", *["---:"] * len(ms)], report_rows))
    add("")
    add(
        f"Mean all-pairs precision: {_f(ap)} "
        + ("✓" if ap >= BAR_PRECISION_MEAN else "✗")
        + f" against the original ≥ {BAR_PRECISION_MEAN:.2f}."
    )
    add("")

    # -- wrong attachment and the floor --------------------------------------
    add("## Wrong attachment and the floor")
    add("")
    add(
        "**Floor:** events produced by someone other than the device's owner, in a session "
        "with no form fill, ÷ events whose device is attachable. Nothing in such a session "
        "says who produced it, so any rule that attaches it can only guess."
    )
    add("")
    add(
        "**The floor is a lower bound** on the unavoidable part, not all of it. It counts "
        "borrowers' events only. An owner's session without a form fill, on a device where "
        "only the borrower filled forms, is just as unidentifiable and is not counted. "
        f"The floor is above the {BAR_WRONG_ATTACHMENT:.3f} bar on every seed, so the bar is "
        f"reported as a miss; see [ADR 0004]({ADR_0004})."
    )
    add("")
    add(
        _table(
            [
                "Seed",
                "Attached events",
                "Wrong",
                "Wrong attachment",
                "Bar",
                "Floor",
                "Floor events",
            ],
            ["---", "---:", "---:", "---:", "---:", "---:", "---:"],
            [
                [
                    str(m["seed"]),
                    f"{m['event_attachment']['attached']:,}",
                    f"{m['event_attachment']['wrong']:,}",
                    _f(m["event_attachment"]["wrong_rate"]),
                    f"≤ {BAR_WRONG_ATTACHMENT:.3f}",
                    _f(m["event_attachment"]["floor"]["rate"]),
                    f"{m['event_attachment']['floor']['unidentifiable']:,}"
                    f" / {m['event_attachment']['floor']['events']:,}",
                ]
                for m in ms
            ],
        )
    )
    add("")

    # -- both-DOBs breakdown -------------------------------------------------
    add("## Same-name relatives with both DOBs present")
    add("")
    add(
        "The bar counts a pair as merged when any unit of one relative shares a profile "
        "with any unit of the other. The breakdown separates the two ways that happens:"
    )
    add("")
    add(
        "- **Contact to contact:** both relatives' CRM contacts in one profile. 01 `v1.1.0` "
        "makes a DOB mismatch a clustering cannot-link, so this is expected to be 0."
    )
    add(
        "- **Only through form fills:** the contacts are apart, but a form fill of one "
        "relative sits with the other relative's contact. Forms carry no DOB; a form with "
        "the same name and the relatives' shared identifier matches both contacts, and "
        "nothing on it says which relative filled it. "
        f"See [ADR 0001]({ADR_0001})."
    )
    add("")
    add(
        _table(
            [
                "Seed",
                "Pairs",
                "Merged",
                "Contact to contact (expected 0)",
                "Only through form fills",
                "Forms involved",
                "Other",
            ],
            ["---", "---:", "---:", "---:", "---:", "---:", "---:"],
            [
                [
                    str(m["seed"]),
                    str(sn_both(m)["pairs"]),
                    str(m["same_name_both_dob"]["merged"]),
                    str(m["same_name_both_dob"]["pairs"]["contact"]),
                    str(m["same_name_both_dob"]["pairs"]["forms_only"]),
                    str(m["same_name_both_dob"]["forms"]),
                    str(m["same_name_both_dob"]["pairs"]["other"]),
                ]
                for m in ms
            ],
        )
    )
    add("")

    # -- hard-case report (acceptance.md format) ------------------------------
    add("## Hard-case report")
    add("")
    add(
        '"Merged" means any unit of one person shares a profile with any unit of the other. '
        "Each cell is merged / pairs in that DOB group."
    )
    add("")
    hard_rows = []
    for m in ms:
        for kind in HAZARD_KINDS:
            cells = m["hard_cases"][kind]
            hard_rows.append(
                [
                    str(m["seed"]),
                    f"`{kind}`",
                    str(sum(cells[g]["pairs"] for g in DOB_GROUPS)),
                    *[f"{cells[g]['merged']} / {cells[g]['pairs']}" for g in DOB_GROUPS],
                ]
            )
    add(
        _table(
            [
                "Seed",
                "Kind",
                "Pairs",
                "Merged, DOB both present",
                "Merged, DOB one missing",
                "Merged, DOB both missing",
            ],
            ["---", "---", "---:", "---:", "---:", "---:"],
            hard_rows,
        )
    )
    add("")
    add("`email_changed` people (two contacts, different emails, same phone):")
    add("")
    ec_rows = []
    for m in ms:
        for r in m["email_changed_rules"]:
            ec_rows.append(
                [str(m["seed"]), r["outcome"], r["decision"], f"`{r['rule']}`", str(r["people"])]
            )
    add(
        _table(
            ["Seed", "Outcome", "01 decision", "01 rule", "People"],
            ["---", "---", "---", "---", "---:"],
            ec_rows,
        )
    )
    add("")

    # -- 01 decisions ----------------------------------------------------------
    add("## 01 pair decisions")
    add("")
    add(
        "REVIEW pairs stay unmerged (02 has no review loop). SPLIT edges are MATCH edges "
        "that 01's clustering cut to keep a conflict or a DOB mismatch apart."
    )
    add("")
    keys = sorted(
        {(d, r) for m in ms for d, rules in m["decisions"].items() if d != "MATCH" for r in rules}
    )
    add(
        _table(
            ["Decision", "Rule", *seed_cols],
            ["---", "---", *["---:"] * len(ms)],
            [
                [d, f"`{r}`", *[f"{m['decisions'].get(d, {}).get(r, 0):,}" for m in ms]]
                for d, r in keys
            ],
        )
    )
    add("")

    # -- device rules ------------------------------------------------------------
    add("## Device rules")
    add("")
    add(
        "All five rules on the same stitch; the pipeline writes (d). "
        f"Bars: attachment ≥ {BAR_ATTACHMENT:.2f}, wrong attachment ≤ {BAR_WRONG_ATTACHMENT:.3f}. "
        f"Why (d): [ADR 0004]({ADR_0004})."
    )
    add("")
    rule_rows = []
    for m in ms:
        for i, (key, name) in enumerate(RULE_NAMES.items()):
            r = m["device_rules"][key]
            rule_rows.append(
                [
                    str(m["seed"]) if i == 0 else "",
                    f"**{name}** (adopted)" if key == ADOPTED_RULE else name,
                    f"{_f(r['rate'])} {'✓' if r['rate'] >= BAR_ATTACHMENT else '✗'}",
                    f"{_f(r['wrong_rate'])} "
                    + ("✓" if r["wrong_rate"] <= BAR_WRONG_ATTACHMENT else "✗"),
                    _f(m["event_attachment"]["floor"]["rate"]),
                    _f(r["fragment_rate"]),
                ]
            )
    add(
        _table(
            ["Seed", "Rule", "Attachment", "Wrong attachment", "Floor", "Fragment"],
            ["---", "---", "---:", "---:", "---:", "---:"],
            rule_rows,
        )
    )
    add("")

    # -- performance ---------------------------------------------------------------
    add("## Performance")
    add("")
    add(
        "Not reported yet. Timings vary between runs, so they stay out of this file; the "
        "`docs/acceptance.md` performance numbers are measured by the `perf-report` job (M7)."
    )
    add("")
    return "\n".join(out)
